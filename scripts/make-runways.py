"""Builds Resources/runways.csv: one row per runway threshold, from the
OurAirports runway table cached by the traffic library
(~/Library/Caches/traffic/runways_ourairports.parquet).

Run with: uv run --with pyarrow --with pandas python scripts/make-runways.py

Columns: airport (ICAO), runway (name of the threshold, e.g. 14R), latitude,
longitude, elevation (ft), bearing (true, from this threshold to the opposite
one: the landing direction), length (ft).
"""

import math
import sys
from pathlib import Path

import pandas as pd

source = Path(sys.argv[1] if len(sys.argv) > 1 else "~/Library/Caches/traffic/runways_ourairports.parquet").expanduser()
out = Path(__file__).resolve().parent.parent / "Resources" / "runways.csv"


def bearing(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    y = math.sin(lo2 - lo1) * math.cos(la2)
    x = math.cos(la1) * math.sin(la2) - math.sin(la1) * math.cos(la2) * math.cos(lo2 - lo1)
    return (math.degrees(math.atan2(y, x)) + 360) % 360


def dms(value):
    """353357.23N or 1394711.59E to decimal degrees."""
    head = value[:-1].split(".")[0]
    degrees = len(head) - 4
    result = int(value[:degrees]) + int(value[degrees:degrees + 2]) / 60 + float(value[degrees + 2:-1]) / 3600
    return -result if value[-1] in "SW" else result


# Runway ends corrected from the published AIP, where OurAirports is wrong.
# Same convention as OurAirports: the physical end of the runway (not a
# displaced threshold) and its elevation (ft).
# RJTT: AIP Japan RJTT AD 2.12, EFF 28 NOV 2024. OurAirports gives the
# displaced threshold of 34R (367 m off) and 34L, 05, 16L 29-43 m off, which
# tilts the 16L/34R bearing by 1.05 deg and 16R/34L by 0.46 deg.
CORRECTIONS = {
    ("RJTT", "16L"): ("353357.23N", "1394711.59E", 21.8),
    ("RJTT", "34R"): ("353222.90N", "1394818.49E", 27.8),
    ("RJTT", "16R"): ("353335.95N", "1394608.64E", 20.5),
    ("RJTT", "34L"): ("353211.76N", "1394708.41E", 18.2),
    ("RJTT", "04"): ("353256.47N", "1394540.60E", 19.0),
    ("RJTT", "22"): ("353402.88N", "1394637.61E", 35.0),
    ("RJTT", "05"): ("353126.41N", "1394812.47E", 45.5),
    ("RJTT", "23"): ("353226.15N", "1394919.61E", 54.7),
}


def corrected(airport, name, lat, lon, elev):
    if (airport, name) not in CORRECTIONS:
        return lat, lon, elev
    la, lo, el = CORRECTIONS[(airport, name)]
    return dms(la), dms(lo), el


runways = pd.read_parquet(source)
rows = []
for r in runways.itertuples():
    if r.closed or not isinstance(r.airport_ident, str) or len(r.airport_ident) != 4:
        continue
    ends = [
        (r.le_ident, *corrected(r.airport_ident, r.le_ident, r.le_latitude_deg, r.le_longitude_deg, r.le_elevation_ft)),
        (r.he_ident, *corrected(r.airport_ident, r.he_ident, r.he_latitude_deg, r.he_longitude_deg, r.he_elevation_ft)),
    ]
    if any(pd.isna(e[1]) or pd.isna(e[2]) or not isinstance(e[0], str) for e in ends):
        continue
    for (name, lat, lon, elev), (_, lat2, lon2, _) in (ends, ends[::-1]):
        if (lat, lon) == (lat2, lon2):
            continue
        elevation = "" if pd.isna(elev) else f"{elev:.0f}"
        length = "" if pd.isna(r.length_ft) else f"{r.length_ft:.0f}"
        rows.append(f"{r.airport_ident},{name},{lat:.6f},{lon:.6f},{elevation},{bearing((lat, lon), (lat2, lon2)):.2f},{length}")

with open(out, "w") as f:
    f.write("# Runway thresholds from OurAirports (via the traffic library cache), generated by\n")
    f.write("# scripts/make-runways.py. Bearing: true, towards the opposite threshold.\n")
    f.write("# Some airports corrected from their AIP (CORRECTIONS in the script).\n")
    f.write("airport,runway,latitude,longitude,elevation,bearing,length\n")
    f.write("\n".join(rows) + "\n")
print(f"{len(rows)} thresholds")
