"""Builds Resources/navaids.csv: named points (fixes, VOR, NDB, DME) to place
the waypoints of a flight plan's field 15, from the navaid table cached by
the traffic library (~/Library/Caches/traffic/traffic_navaid.parquet).

Run with: uv run --with pyarrow --with pandas python scripts/make-navaids.py

Names are not unique worldwide: the reader takes, for each waypoint, the
point of that name closest to the previous one.
"""

import sys
from pathlib import Path

import pandas as pd

source = Path(sys.argv[1] if len(sys.argv) > 1 else "~/Library/Caches/traffic/traffic_navaid.parquet").expanduser()
out = Path(__file__).resolve().parent.parent / "Resources" / "navaids.csv"

navaids = pd.read_parquet(source, columns=["name", "type", "latitude", "longitude"])
navaids = navaids[navaids.type.isin(["FIX", "VOR", "NDB", "DME", "TACAN"])]
navaids = navaids.dropna(subset=["name", "latitude", "longitude"])
# One row per name and place: a VOR and its DME are the same point.
navaids = navaids.assign(lat=navaids.latitude.round(4), lon=navaids.longitude.round(4))
navaids = navaids.drop_duplicates(subset=["name", "lat", "lon"])
with open(out, "w") as f:
    f.write("# Named points from the traffic library's navaid cache, generated by scripts/make-navaids.py.\n")
    for row in navaids.itertuples():
        f.write(f"{row.name},{row.lat:.4f},{row.lon:.4f}\n")
print(f"{len(navaids)} points")
